async function seedData() {
  try {
    console.log('เชื่อมต่อกับ Elasticsearch...');
    
    // Check if Elasticsearch is available
    await client.ping();
    console.log('✓ เชื่อมต่อกับ Elasticsearch สำเร็จ');

    // Check if index exists, delete if it does
    const indexExists = await client.indices.exists({ index: 'movies' });
    if (indexExists) {
      console.log('กำลังลบ index "movies" เดิม...');
      await client.indices.delete({ index: 'movies' });
      console.log('✓ ลบ index เดิมเรียบร้อย');
    }

    // Create index with mapping
    console.log('กำลังสร้าง index "movies"...');
    await client.indices.create({
      index: 'movies',
      mappings: {
        properties: {
          title: { type: 'text' },
          description: { type: 'text' },
          genre: { type: 'keyword' }
        }
      }
    });
    console.log('✓ สร้าง index เรียบร้อย');

    // Insert movies using bulk API for better performance
    console.log(`กำลังเพิ่มข้อมูลภาพยนตร์ ${movies.length} เรื่อง...`);
    const bulkOperations = movies.flatMap(movie => [
      { index: { _index: 'movies' } },
      movie
    ]);

    await client.bulk({
      operations: bulkOperations,
      refresh: true
    });
    console.log('✓ เพิ่มข้อมูลภาพยนตร์ทั้งหมดและ refresh index เรียบร้อย');

    // Verify insertion
    const count = await client.count({ index: 'movies' });
    console.log(`\n✓ เพิ่มข้อมูลภาพยนตร์ทั้งหมด ${count.count} เรื่องลงใน Elasticsearch สำเร็จ`);
    console.log('\nทดสอบค้นหาข้อมูลได้ที่:');
    console.log('  curl "http://localhost:3000/search?q=ผี"');
    console.log('  curl "http://localhost:3000/search?q=รัก"');
    console.log('  curl "http://localhost:3000/search?q=ดราม่า"');

  } catch (error) {
    console.error('เกิดข้อผิดพลาดในการเพิ่มข้อมูล:', error.message);
    process.exit(1);
  }
}

seedData();
